import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {diagnose} from '../app/fidelity-data.ts';
const baseline='1c38bf35c254a891200d3cedecfd57abebe83d8d';
const atlas=JSON.parse(fs.readFileSync('public/models/atlas.json','utf8'));
const data=diagnose(atlas);
assert.deepEqual(data.counts,{parts:2234,concepts:3432,chunks:15});
assert.equal(new Set(atlas.parts.map(p=>p.id)).size,2234);
assert.equal(createHash('sha256').update(fs.readFileSync('package-lock.json')).digest('hex'),'7442e01b64a04a4cc618793bc9ee8a544a9f22b298b3606613e332bf2513fd30');
assert.equal(execFileSync('git',['diff',baseline,'--','public/models'],{encoding:'utf8'}),'');
const anchors={FMA13405:'FJ1541',FMA13406:'FJ1541M',FMA13403:'FJ1542',FMA13404:'FJ1542M',FMA22342:'FJ1431',FMA22343:'FJ1431M',FMA13295:'FJ3131',FMA40120:'FJ1471',FMA40121:'FJ1471M'};
for(const [concept,mesh] of Object.entries(anchors))assert.deepEqual(atlas.concepts.find(c=>c.id===concept)?.elements,[mesh]);
for(const row of [...data.face,...data.viscera,...data.deep])for(const mesh of row.meshIds)assert.ok(atlas.parts.some(p=>p.id===mesh));
assert.equal(data.face.filter(r=>r.status==='NOT_FOUND_IN_FIXED_MANIFEST').length,8);
assert.equal(new Set(data.face.flatMap(r=>r.meshIds)).size,18);
assert.equal(data.skull.length,20);
assert.deepEqual(data.systemParts,{digestive:97,respiratory:119,cardiac:23,urinary:6});
assert.equal(data.deep.length,7);
assert.equal(data.viscera.length,9);
console.log('PASS: counts, unique geometry IDs, nine confirmed anchors, all candidate mappings, 18 face-region meshes, 20 skeletal skull members, system counts, source assets and lockfile unchanged.');
if(process.argv.includes('--export'))fs.writeFileSync('W1_MESH_DIAGNOSTICS.json',JSON.stringify({...data,sourceCommit:baseline,meshMembers:atlas.parts.filter(p=>[...data.face,...data.viscera,...data.deep].some(r=>r.meshIds.includes(p.id))).map(({id,conceptId,name,system,vertexCount,indexCount,chunk})=>({id,conceptId,name,system,vertexCount,indexCount,chunk}))},null,2)+'\n');
